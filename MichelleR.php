    <h1>Resumen de Java</h1>

    <h2>Sintaxis de Java</h2>
    <p>Java es un lenguaje de tipado estático y fuerte, por lo que todas las variables deben declarar su tipo de dato antes de usarse (como int, double, String o boolean). Además, es sensible a mayúsculas y minúsculas.</p>
    <p>Cada instrucción termina con un punto y coma (;) y los bloques de código se agrupan entre llaves ({ }). Todo programa ejecutable requiere un método principal llamado public static void main(String[] args) como punto de entrada.</p>

    <h2> Estructuras Repetitivas</h2>
    <p>Las estructuras repetitivas o bucles permiten ejecutar un bloque de código varias veces. El ciclo for se utiliza cuando se conoce de antemano el número exacto de repeticiones, agrupando la inicialización, condición e incremento en una sola línea.</p>
    <p>El ciclo while evalúa una condición antes de entrar al bloque y se repite mientras sea verdadera. Por otro lado, el ciclo do-while garantiza que el código se ejecute al menos una vez antes de evaluar la condición al final.</p>

    <h2> POO (Atributos y Métodos)</h2>
    <p>En la Programación Orientada a Objetos, una clase funciona como un molde y un objeto es una instancia creada a partir de ella. Los atributos son las variables internas que definen las características o el estado de ese objeto.</p>
    <p>Los métodos son las funciones declaradas dentro de la clase que definen el comportamiento o las acciones que el objeto puede realizar. El acceso a ambos se controla mediante modificadores como public, private y protected.</p>

    <h2> Herencia</h2>
    <p>La herencia permite que una clase hija (subclase) adquiera los atributos y métodos de una clase padre (superclase) para reutilizar código. En Java se aplica utilizando la palabra clave extends en la declaración de la clase hija.</p>
    <p>También se utiliza la palabra clave super para invocar constructores o métodos de la clase padre. Cabe destacar que Java solo admite herencia simple, es decir, una clase hija solo puede heredar directamente de una clase padre.</p>

